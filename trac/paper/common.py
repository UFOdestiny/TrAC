def load_cells():
    """setting -> dict(y, s: {method: out-of-fold or training-free scores}, B: feature blocks, aux, ok)."""
    cells = {}
    for f in sorted(glob.glob(str(C.SCORES / "*.npz"))):
        tag = os.path.basename(f)[:-4]
        o = dict(np.load(f))
        y = o.pop("y").astype(int)
        B = load_cell(tag)
        sc = dict(o)
        for d in raw_baselines(B).values():
            sc.update({k: v for k, v in d.items() if np.isfinite(v).all()})
        fa = C.AUXILIARY / f"{tag}.npz"
        aux = dict(np.load(fa, allow_pickle=True)) if fa.exists() else {}
        if "ids" in aux and len(aux["ids"]) != len(y):  # align per-response statistics to the unique ids
            pos = {str(q): i for i, q in enumerate(aux["ids"])}
            idx = np.array([pos[str(q)] for q in B["ids"]])
            aux = {k: (v[idx] if getattr(v, "ndim", 0) >= 1 and len(v) == len(aux["ids"]) else v) for k, v in aux.items()}
        cells[tag] = {"y": y, "s": sc, "B": B, "aux": aux, "ok": min(y.sum(), (1 - y).sum()) >= MIN_CLASS_COUNT}
    return cells


def macro(cells, name, fn, only_ok=True, filt=None):
    v = [
        fn(c["s"][name], c["y"])
        for t, c in cells.items()
        if (c["ok"] or not only_ok) and name in c["s"] and (filt is None or filt(t))
    ]
    return float(np.mean(v)) if v else float("nan")


def auc(s, y):
    return roc_auc_score(y, s)


def f3(x):
    return "--" if x is None or not np.isfinite(x) else f"{x:.3f}"[1:] if 0 <= x < 1 else f"{x:.3f}"


def best_marks(vals, higher=True):
    """bold best / underline second over finite values."""
    fin = [v for v in vals if np.isfinite(v)]
    if not fin:
        return ["--"] * len(vals)
    srt = sorted(set(fin), reverse=higher)
    out = []
    for v in vals:
        s = f3(v)
        if np.isfinite(v) and v == srt[0]:
            s = r"\textbf{" + s + "}"
        elif len(srt) > 1 and np.isfinite(v) and v == srt[1]:
            s = r"\underline{" + s + "}"
        out.append(s)
    return out


def latency_rel(concurrency=16):
    """Median relative latency over the paired audits (latency/throughput_*.json, trac.pipeline.throughput)
    at one concurrency: every TrAC query ('trac'), the minimal configuration ('trac_min'), and SC@8 from
    the seven extra samples ('sc_8'); SC@2 ('sc_2') comes from the sampling audits (latency/sampling_*.json,
    trac.pipeline.latency). Medians over backbones of each backbone's median."""
    audits = [
        [r for r in json.load(open(f))["runs"] if r["concurrency"] == concurrency]
        for f in sorted(glob.glob(str(C.LATENCY / "throughput_*.json")))
        if not f.endswith("_minimal.json")
    ]
    audits = [a for a in audits if a]
    rel = lambda runs, k: float(np.median([np.median([(r["primary"] + r[k]) / r["primary"] for r in a]) for a in runs]))
    minimal = [json.load(open(f))["runs"] for f in sorted(glob.glob(str(C.LATENCY / "throughput_*_minimal.json")))]
    sampling = [json.load(open(f))["relative"] for f in glob.glob(str(C.LATENCY / "sampling_*.json"))]
    return {
        "trac": rel(audits, "trac"),
        "trac_min": rel(minimal, "minimal"),
        "sc_8": rel(audits, "sc_extra_7"),
        "sc_2": float(np.median([e["sc_2"] for e in sampling])),
    }


def prefix_consistency_cost(cells):
    """Tokens regenerated by prefix consistency relative to the original output tokens (all K traces)."""
    regen = prefix = 0.0
    for tag, c in cells.items():
        fp = C.PREFIX_CONSISTENCY / f"{tag}.json.gz"
        if not fp.exists():
            continue
        PC = {x["id"]: x["traces"] for x in read_json_gz(fp)}
        G = {r["id"]: r for r in read_json_gz(C.GEN / f"{tag}.json.gz")}
        traced = {x["id"] for x in read_json_gz(C.TRAJECTORY / f"{tag}.json.gz")}
        for q in (str(i) for i in c["B"]["ids"]):
            if q not in G or q not in PC or q not in traced:
                continue
            for k in range(1 + len(G[q]["samples"])):
                t = PC[q].get(str(k))
                if t:
                    regen += sum(t["regen_tokens"])
                    prefix += t["prefix_tokens"] / 0.75
    return regen / prefix if prefix else None


